// Generates typed contract ABIs in packages/shared/src/abi/ from the Foundry
// build output. Run `forge build` in contracts/ first.
//   pnpm --filter @bbm/shared run gen:abi
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");
const outDir = resolve(repoRoot, "contracts/out");
const abiDir = resolve(here, "../src/abi");

const CONTRACTS = ["AuditorStaking", "BountyEscrow", "DisputeResolution"] as const;

async function main(): Promise<void> {
  await mkdir(abiDir, { recursive: true });
  for (const name of CONTRACTS) {
    const artifactPath = resolve(outDir, `${name}.sol`, `${name}.json`);
    const artifact = JSON.parse(await readFile(artifactPath, "utf8")) as { abi: unknown[] };
    const constName = `${name[0]!.toLowerCase()}${name.slice(1)}Abi`;
    const body = [
      "// Generated by scripts/gen-abi.ts from contracts/out. Do not edit.",
      `export const ${constName} = ${JSON.stringify(artifact.abi, null, 2)} as const;`,
      "",
    ].join("\n");
    const target = resolve(abiDir, `${name[0]!.toLowerCase()}${name.slice(1)}.ts`);
    await writeFile(target, body);
    console.log(`wrote ${target}`);
  }
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
